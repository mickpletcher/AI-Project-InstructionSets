"""Offline repository checks. No network, third-party packages, or model calls."""
import argparse
import json
import re
from pathlib import Path, PurePosixPath
from urllib.parse import unquote, urlsplit

PLATFORMS = ('claude', 'openai/chatgpt', 'openai/codex', 'microsoft/copilot', 'cursor', 'gemini', 'perplexity')
SECTIONS = ('Purpose', 'Project context', 'Scope', 'Workflow', 'Constraints', 'Output expectations', 'Help')
CASES = ('Happy path', 'Missing context', 'Boundary case')
REQUIRED = ('README.md', 'LICENSE', 'CONTRIBUTING.md', 'CODE_OF_CONDUCT.md', 'SECURITY.md', 'SUPPORT.md', 'ACCESSIBILITY.md', 'changelog.md', 'shared/instruction-set-standard.md', 'docs/installation.md', '.github/workflows/validate.yml')


def read_json(path, errors):
    try:
        return json.loads(path.read_text(encoding='utf-8'))
    except (OSError, ValueError) as exc:
        errors.append(f'{path.name}: cannot read JSON: {exc}')
        return None


def check_set(root, folder, platform, errors):
    for filename in ('README.md', 'instructions.md', 'metadata.json', 'tests.md'):
        path = folder / filename
        if not path.is_file() or not path.read_text(encoding='utf-8').strip():
            errors.append(f'{folder.relative_to(root)}/{filename}: missing or empty')
    for filename, headings in (('instructions.md', SECTIONS), ('tests.md', CASES)):
        path = folder / filename
        if path.is_file():
            actual = set(re.findall(r'^## (.+?)\s*$', path.read_text(encoding='utf-8'), re.M))
            for heading in headings:
                if heading not in actual:
                    errors.append(f'{folder.relative_to(root)}/{filename}: missing heading {heading}')
    meta = read_json(folder / 'metadata.json', errors)
    if not isinstance(meta, dict):
        errors.append(f'{folder.relative_to(root)}: metadata must be an object')
        return None
    for key in ('id', 'name', 'summary', 'platform', 'surface', 'version', 'status'):
        if not isinstance(meta.get(key), str) or not meta[key].strip():
            errors.append(f'{folder.relative_to(root)}: invalid {key}')
    if meta.get('id') != folder.name or not re.fullmatch(r'[a-z0-9]+(?:-[a-z0-9]+)*', folder.name):
        errors.append(f'{folder.relative_to(root)}: id must match kebab-case folder')
    if meta.get('platform') != platform:
        errors.append(f'{folder.relative_to(root)}: platform mismatch')
    if not re.fullmatch(r'(0|[1-9]\d*)\.(0|[1-9]\d*)\.(0|[1-9]\d*)', str(meta.get('version', ''))):
        errors.append(f'{folder.relative_to(root)}: version must be x.y.z')
    if meta.get('status') not in ('draft', 'published'):
        errors.append(f'{folder.relative_to(root)}: invalid status')
    return meta


def render_catalog(entries):
    lines = ['# Instruction-set catalog', '', '<!-- Generated by tools/validate.py; edit catalog.json and metadata.json instead. -->', '']
    if not entries:
        lines += ['No instruction sets are published yet. The [example](templates/example-project/) is an authoring template, not a shipped set.']
    for path, meta in entries:
        # Plain metadata cannot inject Markdown links into the generated inventory.
        name = re.sub(r'[\[\]<>`*\\]', '', meta['name']).replace('\n', ' ')
        summary = re.sub(r'[\[\]<>`*\\]', '', meta['summary']).replace('\n', ' ')
        lines += [f"- [{name}]({path}/README.md) ({meta['platform']}, {meta['version']}): {summary}"]
    return '\n'.join(lines) + '\n'


def inline_destinations(text):
    """Yield inline Markdown destinations, including escapes, nesting and titles.

    This is a scoped file-link checker, not a complete CommonMark renderer.
    Reference-style links and heading anchors are intentionally out of scope.
    """
    for match in re.finditer(r'(?<!!)\[(?:\\.|[^\]\\])*\]\(|!\[(?:\\.|[^\]\\])*\]\(', text):
        i = match.end()
        while i < len(text) and text[i].isspace():
            i += 1
        target = []
        angle = i < len(text) and text[i] == '<'
        if angle:
            i += 1
        depth = 0
        while i < len(text):
            char = text[i]
            if char == '\\' and i + 1 < len(text) and text[i + 1] in r'!"#$%&\'()*+,-./:;<=>?@[\]^_`{|}~':
                target.append(text[i + 1])
                i += 2
                continue
            if angle:
                if char == '>':
                    i += 1
                    break
                if char in '\r\n<':
                    break
            else:
                if char == '(':
                    depth += 1
                elif char == ')':
                    if depth == 0:
                        break
                    depth -= 1
                elif char.isspace():
                    break
            target.append(char)
            i += 1
        else:
            continue
        if angle and (i == 0 or text[i - 1] != '>'):
            continue
        if depth:
            continue
        # A destination may be followed by whitespace and an optional title.
        end = i
        while end < len(text) and text[end].isspace():
            end += 1
        if end > i and end < len(text) and text[end] in ('"', "'", '('):
            close = ')' if text[end] == '(' else text[end]
            end += 1
            while end < len(text):
                if text[end] == '\\' and end + 1 < len(text):
                    end += 2
                    continue
                if text[end] == close:
                    end += 1
                    break
                end += 1
            else:
                continue
            while end < len(text) and text[end].isspace():
                end += 1
        if end < len(text) and text[end] == ')':
            yield ''.join(target)


def check_links(root, errors):
    for path in root.rglob('*.md'):
        if any(part.startswith('.') for part in path.relative_to(root).parts[:-1]):
            continue
        text = re.sub(r'```.*?```', '', path.read_text(encoding='utf-8'), flags=re.S)
        for target in inline_destinations(text):
            try:
                url = urlsplit(target)
            except ValueError:
                errors.append(f'{path.relative_to(root)}: malformed link {target}')
                continue
            if url.scheme or url.netloc or not url.path:
                continue
            dest = (path.parent / unquote(url.path)).resolve()
            if not dest.is_relative_to(root.resolve()) or not dest.exists():
                errors.append(f'{path.relative_to(root)}: broken or escaping relative link {target}')


def validate(root, write_catalog=False):
    root = Path(root).resolve()
    errors = []
    for filename in REQUIRED:
        if not (root / filename).is_file():
            errors.append(f'{filename}: missing required file')
    inventory = read_json(root / 'catalog.json', errors)
    if not isinstance(inventory, dict) or inventory.get('schema_version') != 1 or not isinstance(inventory.get('instruction_sets'), list):
        errors.append('catalog.json: expected schema_version 1 and instruction_sets array')
        inventory = {'instruction_sets': []}
    discovered = {}
    for platform in PLATFORMS:
        area = root / platform / 'instruction-sets'
        if not area.is_dir() or not (root / platform / 'README.md').is_file():
            errors.append(f'{platform}: missing platform scaffold')
        if area.is_dir():
            for folder in sorted(area.iterdir()):
                if folder.is_dir():
                    discovered[folder.relative_to(root).as_posix()] = check_set(root, folder, platform, errors)
    check_set(root, root / 'templates/example-project', 'template', errors)
    entries, seen = [], set()
    for path in inventory['instruction_sets']:
        if not isinstance(path, str) or '\\' in path or PurePosixPath(path).is_absolute() or '..' in PurePosixPath(path).parts:
            errors.append(f'catalog.json: unsafe path {path!r}')
            continue
        if path in seen:
            errors.append(f'catalog.json: duplicate path {path}')
        seen.add(path)
        meta = discovered.get(path)
        if not meta:
            errors.append(f'catalog.json: unknown instruction set {path}')
        elif meta.get('status') != 'published':
            errors.append(f'catalog.json: {path} is not published')
        elif all(isinstance(meta.get(k), str) for k in ('name', 'summary', 'platform', 'version')):
            entries.append((path, meta))
    for path, meta in discovered.items():
        if meta and meta.get('status') == 'published' and path not in seen:
            errors.append(f'catalog.json: published set missing: {path}')
    generated = render_catalog(sorted(entries))
    catalog = root / 'CATALOG.md'
    if write_catalog and not errors:
        catalog.write_text(generated, encoding='utf-8', newline='\n')
    elif not catalog.is_file() or catalog.read_text(encoding='utf-8') != generated:
        errors.append('CATALOG.md: stale; run python tools/validate.py --write-catalog')
    check_links(root, errors)
    return errors


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--write-catalog', action='store_true')
    args = parser.parse_args()
    errors = validate(Path(__file__).resolve().parents[1], args.write_catalog)
    for error in errors:
        print(f'ERROR: {error}')
    if not errors:
        print('Repository validation passed (static checks only; no host/model tests).')
    return bool(errors)


if __name__ == '__main__':
    raise SystemExit(main())
